use std::sync::LazyLock;

use crate::{Bitboard, Color, Square};

pub fn knight(sq: Square) -> Bitboard {
    KNIGHT[sq.index()]
}

pub fn king(sq: Square) -> Bitboard {
    KING[sq.index()]
}

/// Squares a pawn of `color` on `sq` attacks.
pub fn pawn(color: Color, sq: Square) -> Bitboard {
    PAWN[color.index()][sq.index()]
}

pub fn bishop(sq: Square, occupied: Bitboard) -> Bitboard {
    let s = &*SLIDERS;
    s.table[s.bishop[sq.index()].index(occupied)]
}

pub fn rook(sq: Square, occupied: Bitboard) -> Bitboard {
    let s = &*SLIDERS;
    s.table[s.rook[sq.index()].index(occupied)]
}

pub fn queen(sq: Square, occupied: Bitboard) -> Bitboard {
    bishop(sq, occupied) | rook(sq, occupied)
}

/// Builds a `[Bitboard; 64]` at compile time from `|b| attacks of the single-square board b`.
macro_rules! leaper_table {
    (|$b:ident| $attacks:expr) => {{
        let mut table = [Bitboard::EMPTY; 64];
        let mut i = 0;
        while i < 64 {
            let $b = Square::from_index(i).bb();
            table[i] = $attacks;
            i += 1;
        }
        table
    }};
}

static KNIGHT: [Bitboard; 64] = leaper_table!(|b| {
    let (n, s, e, w) = (b.north(), b.south(), b.east(), b.west());
    Bitboard(
        n.north_east().0
            | n.north_west().0
            | s.south_east().0
            | s.south_west().0
            | e.north_east().0
            | e.south_east().0
            | w.north_west().0
            | w.south_west().0,
    )
});

static KING: [Bitboard; 64] = leaper_table!(|b| {
    let row = Bitboard(b.0 | b.east().0 | b.west().0);
    Bitboard((row.0 | row.north().0 | row.south().0) & !b.0)
});

static PAWN: [[Bitboard; 64]; 2] = [
    leaper_table!(|b| Bitboard(b.north_east().0 | b.north_west().0)),
    leaper_table!(|b| Bitboard(b.south_east().0 | b.south_west().0)),
];

const BISHOP_DIRS: [(i8, i8); 4] = [(1, 1), (1, -1), (-1, 1), (-1, -1)];
const ROOK_DIRS: [(i8, i8); 4] = [(0, 1), (0, -1), (1, 0), (-1, 0)];

/// Reference slider attacks by walking rays; used to build and verify the magic tables.
fn slider_slow(sq: Square, occupied: Bitboard, dirs: &[(i8, i8)]) -> Bitboard {
    let mut attacks = Bitboard::EMPTY;
    for &(df, dr) in dirs {
        let (mut f, mut r) = (sq.file() as i8, sq.rank() as i8);
        loop {
            (f, r) = (f + df, r + dr);
            if !(0..8).contains(&f) || !(0..8).contains(&r) {
                break;
            }
            let to = Square::new(f as u8, r as u8);
            attacks |= to.bb();
            if occupied.contains(to) {
                break;
            }
        }
    }
    attacks
}

struct Magic {
    mask: Bitboard,
    magic: u64,
    shift: u32,
    offset: usize,
}

impl Magic {
    fn index(&self, occupied: Bitboard) -> usize {
        self.offset + ((occupied & self.mask).0.wrapping_mul(self.magic) >> self.shift) as usize
    }
}

struct Sliders {
    bishop: [Magic; 64],
    rook: [Magic; 64],
    table: Vec<Bitboard>,
}

static SLIDERS: LazyLock<Sliders> = LazyLock::new(|| {
    let mut table = Vec::new();
    let bishop =
        Square::ALL.map(|sq| fill(sq, &BISHOP_DIRS, BISHOP_MAGICS[sq.index()], &mut table));
    let rook = Square::ALL.map(|sq| fill(sq, &ROOK_DIRS, ROOK_MAGICS[sq.index()], &mut table));
    Sliders {
        bishop,
        rook,
        table,
    }
});

/// Appends the attack slice of `sq` to `table`.
fn fill(sq: Square, dirs: &[(i8, i8)], magic: u64, table: &mut Vec<Bitboard>) -> Magic {
    let mask = relevant_mask(sq, dirs);
    let m = Magic {
        mask,
        magic,
        shift: 64 - mask.count(),
        offset: table.len(),
    };
    table.resize(table.len() + (1 << mask.count()), Bitboard::EMPTY);
    for occupied in subsets(mask) {
        table[m.index(occupied)] = slider_slow(sq, occupied, dirs);
    }
    m
}

/// Squares whose occupancy affects slider attacks from `sq`. Edge squares never block
/// anything behind them, unless the slider stands on that edge.
fn relevant_mask(sq: Square, dirs: &[(i8, i8)]) -> Bitboard {
    let edges = ((Bitboard::rank(0) | Bitboard::rank(7)) & !Bitboard::rank(sq.rank()))
        | ((Bitboard::FILE_A | Bitboard::FILE_H) & !Bitboard::file(sq.file()));
    slider_slow(sq, Bitboard::EMPTY, dirs) & !edges
}

/// All subsets of `mask` (Carry-Rippler), starting from the empty one.
fn subsets(mask: Bitboard) -> impl Iterator<Item = Bitboard> {
    std::iter::successors(Some(0u64), move |&s| {
        let next = s.wrapping_sub(mask.0) & mask.0;
        (next != 0).then_some(next)
    })
    .map(Bitboard)
}

